"""UML activity-diagram shape recognition -- the vocabulary this adapter
used to be entirely missing: a filled initial-node dot, a bullseye final
node (hollow ring + nested solid dot), solid fork/join synchronization
bars, rounded-rectangle activity nodes, and a swimlane divider. None of
these existed as detectable shapes before (only rectangle/diamond/circle
were recognized at all -- see adapters/diagram/README.md's "Known
limitations").

Uses tests/fixtures/activity_diagram_clean.png, generated by
tests/fixtures/generate_diagram_fixture_activity.py: an 8-node UML activity
flow (initial -> Receive Order -> fork -> {Pack Items, Charge Payment} ->
join -> Ship Order -> final) plus one swimlane divider.

Every assertion below would fail against the adapter before this change:
none of node-initial/node-final/fork-join/node-activity/swimlane existed as
shape values, and the real signal that makes them possible -- sampling a
contour's own interior darkness to tell a solid-filled glyph apart from a
hollow outline of the identical silhouette -- didn't exist either.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

FIXTURE = ROOT / "tests" / "fixtures" / "activity_diagram_clean.png"


def _build():
    from adapters.diagram.adapter import build_artifact

    return build_artifact(FIXTURE)


def test_all_new_uml_shapes_are_detected_exactly_once():
    artifact = _build()
    nodes = [r for r in artifact["regions"] if r["type"] == "node"]
    shapes = [n["shape"] for n in nodes]

    assert shapes.count("node-initial") == 1, f"expected exactly 1 initial node, got shapes: {shapes}"
    assert shapes.count("node-final") == 1, f"expected exactly 1 final node, got shapes: {shapes}"
    assert shapes.count("fork-join") == 2, f"expected exactly 2 fork/join bars, got shapes: {shapes}"
    assert shapes.count("node-activity") == 4, f"expected exactly 4 rounded-rect activity nodes, got shapes: {shapes}"
    assert len(nodes) == 8, f"expected exactly 8 total node regions, got {len(nodes)}: {shapes}"


def test_solid_fill_signal_is_real_not_confused_with_hollow_shapes():
    """The one thing that makes node-initial/node-final/fork-join possible
    at all: a solid-filled contour and a hollow outline of the identical
    silhouette have the SAME fill_ratio, so a separate interior-darkness
    signal is required. Directly exercises that helper rather than only
    the end-to-end shape labels above.
    """
    import cv2

    from adapters.diagram.adapter import SOLID_FILL_MEAN_THRESHOLD, _load_binary, _mean_interior_intensity

    binary = _load_binary(FIXTURE)
    contours, _ = cv2.findContours(binary, cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)

    # At least one contour in this image must read as clearly solid (the
    # initial dot, the final node's inner dot, or a fork/join bar) and at
    # least one must read as clearly hollow (an activity box's outline) --
    # proves the signal actually varies on real data, not a constant.
    means = [_mean_interior_intensity(binary, c) for c in contours if cv2.contourArea(c) > 200]
    assert any(m >= SOLID_FILL_MEAN_THRESHOLD for m in means), "expected at least one solid-filled contour"
    assert any(m < SOLID_FILL_MEAN_THRESHOLD for m in means), "expected at least one hollow contour"


def test_node_activity_labels_are_ocrd():
    artifact = _build()
    labels = {r["text"] for r in artifact["regions"] if r["shape"] == "node-activity"}
    assert labels == {"Receive Order", "Pack Items", "Charge Payment", "Ship Order"}, labels


def test_initial_and_final_and_fork_join_carry_no_label():
    """These are pure UML glyphs with no text of their own by convention --
    OCR is deliberately skipped for them (see adapter._NO_LABEL_SHAPES), so
    their text must be None even though the OCR engine is available.
    """
    artifact = _build()
    no_label_shapes = {"node-initial", "node-final", "fork-join"}
    for r in artifact["regions"]:
        if r.get("shape") in no_label_shapes:
            assert r["text"] is None, f"{r['id']} ({r['shape']}) should carry no OCR'd text, got {r['text']!r}"


def test_swimlane_divider_is_detected_as_its_own_region_type():
    artifact = _build()
    swimlanes = [r for r in artifact["regions"] if r["type"] == "swimlane"]
    assert len(swimlanes) == 1, f"expected exactly 1 swimlane divider, got {len(swimlanes)}"
    assert swimlanes[0]["shape"] == "swimlane-divider"
    assert 0.0 < swimlanes[0]["confidence"] <= 1.0


def test_full_topology_reconstructs_the_activity_flow():
    """End-to-end: initial -> Receive Order -> fork -> {Pack Items, Charge
    Payment} -> join -> Ship Order -> final, all 8 edges present and every
    edge's two endpoints resolve to real node ids (checked both directly
    and via the adapter's own edges-reference-existing-nodes check).
    """
    artifact = _build()
    id_to_shape = {r["id"]: r["shape"] for r in artifact["regions"] if r["type"] == "node"}
    edges = [r for r in artifact["regions"] if r["type"] == "edge"]
    assert len(edges) == 8, f"expected 8 edges, got {len(edges)}"

    def _targets(edge):
        return {rel["target"] for rel in edge["relationships"] if rel["type"] == "connects-to"}

    shape_pairs = [tuple(sorted(id_to_shape[t] for t in _targets(e))) for e in edges]
    expected_pairs = [
        ("node-activity", "node-initial"),  # initial -> Receive Order
        ("fork-join", "node-activity"),  # Receive Order -> fork
        ("fork-join", "node-activity"),  # fork -> Pack Items
        ("fork-join", "node-activity"),  # fork -> Charge Payment
        ("fork-join", "node-activity"),  # Pack Items -> join
        ("fork-join", "node-activity"),  # Charge Payment -> join
        ("fork-join", "node-activity"),  # join -> Ship Order
        ("node-activity", "node-final"),  # Ship Order -> final
    ]
    assert sorted(shape_pairs) == sorted(expected_pairs), shape_pairs

    check = next(c for c in artifact["checks"] if c["name"] == "edges-reference-existing-nodes")
    assert check["passed"] is True, check["detail"]


